function requestDateInstruction(value: string | undefined): string {
  if (value === undefined)
    return "Дата запроса неизвестна. Не выводи текущую дату из старой переписки и не выдумывай её.";
  if (
    !/^\d{4}-\d{2}-\d{2}$/.test(value) ||
    !Number.isFinite(Date.parse(value + "T00:00:00.000Z")) ||
    new Date(value + "T00:00:00.000Z").toISOString().slice(0, 10) !== value
  )
    throw new Error("Invalid assistant request date");
  return (
    "Дата запроса (UTC): " +
    value +
    ". Это дата запроса, а не подтверждение проверки или обновления источника."
  );
}

